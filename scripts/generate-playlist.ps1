# Builds playlist.js from everything in the images/ and music/ folders.
# Run it again whenever you add or remove images or music.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$imageExt = '.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif'
$audioExt = '.mp3', '.ogg', '.opus', '.wav', '.m4a', '.flac'

function Get-RelativePath($file) { $file.FullName.Substring($root.Length + 1).Replace('\', '/') }
function ConvertTo-JsString($s) { '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

$images = @()
$imageDir = Join-Path $root 'images'
if (Test-Path $imageDir) {
  Get-ChildItem $imageDir -Directory | Sort-Object Name | ForEach-Object {
    $category = $_.Name
    Get-ChildItem $_.FullName -File -Recurse | Where-Object { $imageExt -contains $_.Extension.ToLower() } | Sort-Object FullName |
      ForEach-Object { $images += "  {src:$(ConvertTo-JsString (Get-RelativePath $_)),cat:$(ConvertTo-JsString $category)}" }
  }
}

$music = @()
$musicDir = Join-Path $root 'music'
if (Test-Path $musicDir) {
  Get-ChildItem $musicDir -File | Where-Object { $audioExt -contains $_.Extension.ToLower() } | Sort-Object Name |
    ForEach-Object { $music += "  $(ConvertTo-JsString (Get-RelativePath $_))" }
}

$js = "// Generated by scripts/generate-playlist - do not edit by hand.`n" +
      "window.MANIFEST_IMAGES = [`n" + ($images -join ",`n") + "`n];`n" +
      "window.MANIFEST_MUSIC = [`n" + ($music -join ",`n") + "`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'playlist.js'), $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Playlist updated: $($images.Count) images, $($music.Count) tracks."
