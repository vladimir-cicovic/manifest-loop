#!/usr/bin/env bash
# Builds playlist.js from everything in the images/ and music/ folders.
# Run it again whenever you add or remove images or music.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

js_string() {
  local s=${1//\\/\\\\}
  s=${s//\"/\\\"}
  printf '"%s"' "$s"
}

images=()
if [ -d images ]; then
  while IFS= read -r -d '' dir; do
    category="$(basename "$dir")"
    while IFS= read -r -d '' file; do
      images+=("  {src:$(js_string "$file"),cat:$(js_string "$category")}")
    done < <(find "images/$category" -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.gif' -o -iname '*.avif' \) -print0 | sort -z)
  done < <(find images -mindepth 1 -maxdepth 1 -type d -print0 | sort -z)
fi

music=()
if [ -d music ]; then
  while IFS= read -r -d '' file; do
    music+=("  $(js_string "$file")")
  done < <(find music -maxdepth 1 -type f \( -iname '*.mp3' -o -iname '*.ogg' -o -iname '*.opus' -o -iname '*.wav' -o -iname '*.m4a' -o -iname '*.flac' \) -print0 | sort -z)
fi

join() { local IFS=$'\n'; local out="" first=1; for x in "$@"; do if [ $first -eq 1 ]; then out="$x"; first=0; else out="$out,"$'\n'"$x"; fi; done; printf '%s' "$out"; }

{
  echo "// Generated by scripts/generate-playlist - do not edit by hand."
  echo "window.MANIFEST_IMAGES = ["
  join "${images[@]+"${images[@]}"}"
  echo
  echo "];"
  echo "window.MANIFEST_MUSIC = ["
  join "${music[@]+"${music[@]}"}"
  echo
  echo "];"
} > playlist.js

echo "Playlist updated: ${#images[@]} images, ${#music[@]} tracks."
